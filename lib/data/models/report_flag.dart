import '../../core/constants/report_enums.dart';

/// Report abuse flag model from DATA_MODEL.md §4.4.
///
/// Records user reports of spam, inappropriate content, false information,
/// personal data exposure, or other issues.
class ReportFlag {
  const ReportFlag({
    required this.id,
    required this.reportId,
    required this.reporterId,
    required this.reason,
    this.details,
    this.reviewStatus = FlagReviewStatus.open,
    required this.createdAt,
  });

  final String id;
  final String reportId;
  final String reporterId;
  final FlagReason reason;
  final String? details;
  final FlagReviewStatus reviewStatus;
  final DateTime createdAt;

  ReportFlag copyWith({
    String? id,
    String? reportId,
    String? reporterId,
    FlagReason? reason,
    String? details,
    FlagReviewStatus? reviewStatus,
    DateTime? createdAt,
  }) {
    return ReportFlag(
      id: id ?? this.id,
      reportId: reportId ?? this.reportId,
      reporterId: reporterId ?? this.reporterId,
      reason: reason ?? this.reason,
      details: details ?? this.details,
      reviewStatus: reviewStatus ?? this.reviewStatus,
      createdAt: createdAt ?? this.createdAt,
    );
  }

  /// Deserializes a Supabase row into a [ReportFlag].
  factory ReportFlag.fromMap(Map<String, dynamic> map) {
    return ReportFlag(
      id: map['id'] as String,
      reportId: map['report_id'] as String,
      reporterId: map['reporter_id'] as String,
      reason: FlagReason.values.firstWhere(
        (r) => r.key == map['reason'],
        orElse: () => FlagReason.other,
      ),
      details: map['details'] as String?,
      reviewStatus: FlagReviewStatus.values.firstWhere(
        (s) => s.key == map['review_status'],
        orElse: () => FlagReviewStatus.open,
      ),
      createdAt: DateTime.tryParse(map['created_at'] as String? ?? '') ??
          DateTime.now(),
    );
  }

  /// Serialization adhering to the least-privilege column INSERT grant on public.report_flags:
  /// (report_id, reporter_id, reason, details).
  /// Excludes `id`, `review_status`, and `created_at` which are generated by PostgreSQL defaults.
  Map<String, dynamic> toInsertMap() {
    return {
      'report_id': reportId,
      'reporter_id': reporterId,
      'reason': reason.key,
      if (details != null && details!.trim().isNotEmpty)
        'details': details!.trim(),
    };
  }
}
